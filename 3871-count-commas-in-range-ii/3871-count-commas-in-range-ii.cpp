class Solution {
public:
    long long countCommas(long long n) {
        if(n < 1000) return 0;

        if(n < 1000000) {
            return n - 1000 + 1;
        }

        if(n < 1000000000) {
            return (999999 - 1000 + 1)
                 + 2LL * (n - 1000000 + 1);
        }

        if(n < 1000000000000LL) {
            return (999999 - 1000 + 1)
                 + (999999999 - 1000000 + 1) * 2LL
                 + 3LL * (n - 1000000000 + 1);
        }

        if(n < 1000000000000000LL) {
            return (999999 - 1000 + 1)
                 + (999999999 - 1000000 + 1) * 2LL
                 + (999999999999 - 1000000000 + 1) * 3LL
                 + 4LL * (n - 1000000000000LL + 1);
        }

        if(n < 1000000000000000000LL) {
            return (999999 - 1000 + 1)
                 + (999999999 - 1000000 + 1) * 2LL
                 + (999999999999 - 1000000000 + 1) * 3LL
                 + (999999999999999 - 1000000000000LL + 1) * 4LL
                 + 5LL * (n - 1000000000000000LL + 1);
        }

        return (999999 - 1000 + 1)
             + (999999999 - 1000000 + 1) * 2LL
             + (999999999999 - 1000000000 + 1) * 3LL
             + (999999999999999 - 1000000000000LL + 1) * 4LL
             + (999999999999999999LL - 1000000000000000LL + 1) * 5LL
             + 6LL * (n - 1000000000000000000LL + 1);
    }
};